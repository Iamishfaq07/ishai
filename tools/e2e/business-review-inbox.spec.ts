import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";

test("Review inbox presentation: delayed responses, scoped discovery, errors and accessible queue design", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `inbox-${crypto.randomUUID().slice(0, 8)}.com`; const email = `owner@${domain}`;
  expect((await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Inbox Owner", password: "correct horse battery" } })).status()).toBe(201);
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = /verify-email\?token=([\w-]+)/.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token } })).ok()).toBe(true);
  const company = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Northstar Review Inbox", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(company.status(), await company.text()).toBe(201); const cid = (await company.json()).id as string;
  const base = `${API}/v1/business/companies/${cid}/workflow-studio`;
  const yesterday = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
  const tomorrow = new Date(Date.now() + 86400000).toISOString().slice(0, 10);
  // Explicit presentation fixtures complement the real multi-user review/handoff/decision integration flow.
  const row = { id: "engineering", job_id: "job-a", job_title: "Platform engineer", run_id: "run-a", step_title: "Review engineering launch", requested_at: "2026-10-28T10:00:00Z", due_date: yesterday, overdue: true, snoozed_until: null, path: `/business/app/${cid}/workflow-studio?job=job-a&run=run-a` };
  const paused = { ...row, id: "design", job_id: "job-b", job_title: "Product designer", step_title: "Review design evidence", requested_at: "2026-10-29T10:00:00Z", due_date: tomorrow, overdue: false, snoozed_until: `${tomorrow}T00:00:00Z` };
  const undated = { ...row, id: "panel", step_title: "Confirm interview panel", requested_at: "2026-10-01T10:00:00Z", due_date: null, overdue: false };
  const all = [row, paused, undated, ...Array.from({ length: 47 }, (_, i) => ({ ...undated, id: `extra-${i}`, job_id: "job-c", job_title: "Operations", step_title: `Fixture checkpoint ${i + 1}` }))];
  let holdAll = true; let failOverdue = false; let excludeEngineering = false; const held: Array<() => void> = [];
  await page.route(`${base}/review-inbox/mine?*`, async route => {
    const view = new URL(route.request().url()).searchParams.get("view");
    if (view === "all" && holdAll) await new Promise<void>(resolve => held.push(resolve));
    if (view === "overdue" && failOverdue) { await route.fulfill({ status: 503, json: { detail: "Temporary queue failure" } }); return; }
    const items = view === "overdue" ? [row] : view === "snoozed" ? [paused] : all.filter(item => !excludeEngineering || item.job_id !== "job-a");
    await route.fulfill({ json: { items, truncated: view === "all" && items.length === 50 } });
  });
  const writes: string[] = [];
  page.on("request", request => { if (request.url().includes("/v1/business/") && !["GET", "OPTIONS"].includes(request.method())) writes.push(request.url()); });
  await page.goto(`/business/app/${cid}/workflow-reviews`);
  await expect.poll(() => held.length).toBeGreaterThan(0);
  await page.getByLabel("Review inbox filter", { exact: true }).selectOption("overdue");
  await expect(page.getByRole("heading", { name: row.step_title, exact: true })).toBeVisible();
  await page.getByLabel("Review inbox filter", { exact: true }).selectOption("snoozed");
  await expect(page.getByRole("heading", { name: paused.step_title, exact: true })).toBeVisible();
  const late = page.waitForResponse(response => response.url().endsWith("review-inbox/mine?view=all"));
  holdAll = false; held.forEach(resolve => resolve());
  await (await late).finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(page.getByRole("heading", { name: row.step_title, exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: paused.step_title, exact: true })).toBeVisible();
  await page.getByLabel("Review inbox filter", { exact: true }).selectOption("all");
  await expect(page.getByText(/Showing the first 50 current requests/)).toBeVisible();
  await page.getByLabel("Role in loaded reviews", { exact: true }).selectOption("job-a");
  await page.getByLabel("Search loaded reviews", { exact: true }).fill("panel");
  await expect(page.getByRole("list", { name: "Loaded checkpoint reviews", exact: true }).getByRole("heading")).toHaveText([undated.step_title]);
  await page.getByLabel("Search loaded reviews", { exact: true }).fill("no match");
  await expect(page.getByRole("heading", { name: "No loaded requests match these filters.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Show all loaded reviews", exact: true }).click();
  await page.getByLabel("Search loaded reviews", { exact: true }).fill("review");
  await page.getByLabel("Order loaded reviews", { exact: true }).selectOption("requested");
  await expect(page.getByRole("list", { name: "Loaded checkpoint reviews", exact: true }).getByRole("heading")).toHaveText([row.step_title, paused.step_title]);
  failOverdue = true;
  await page.getByLabel("Review inbox filter", { exact: true }).selectOption("overdue");
  await expect(page.getByRole("button", { name: "Retry", exact: true })).toBeVisible();
  await expect(page.getByRole("list", { name: "Loaded checkpoint reviews", exact: true })).toHaveCount(0);
  failOverdue = false;
  await page.getByRole("button", { name: "Retry", exact: true }).click();
  await expect(page.getByRole("heading", { name: row.step_title, exact: true })).toBeVisible();
  await page.getByLabel("Review inbox filter", { exact: true }).selectOption("all");
  await expect(page.getByRole("heading", { name: paused.step_title, exact: true })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: info.outputPath("review-inbox-desktop.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("review-inbox-mobile-dark.png"), fullPage: true });
  await page.getByLabel("Role in loaded reviews", { exact: true }).selectOption("job-a");
  excludeEngineering = true;
  await page.getByRole("button", { name: "Refresh review inbox", exact: true }).click();
  await expect(page.getByRole("option", { name: "Selected role is outside this loaded view", exact: true })).toHaveCount(1);
  await expect(page.getByRole("heading", { name: "No loaded requests match these filters.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Show all loaded reviews", exact: true }).click();
  await expect(page.getByText("48 of 48 loaded requests shown", { exact: true })).toBeVisible();
  expect(writes).toEqual([]);
});
