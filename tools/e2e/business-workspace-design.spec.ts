import AxeBuilder from "@axe-core/playwright";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { expect, test } from "@playwright/test";

const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";
async function mailToken(email: string, pattern: RegExp) {
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = pattern.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  return token;
}

test("Business workspace: real dashboard data, grouped search, mobile navigation and interviewer presentation", async ({ page, context, browser }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `design-${crypto.randomUUID().slice(0, 8)}.com`; const email = `owner@${domain}`;
  const registration = await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Design Owner", password: "correct horse battery" } });
  expect(registration.status(), await registration.text()).toBe(201);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token: await mailToken(email, /verify-email\?token=([\w-]+)/) } })).ok()).toBe(true);
  const created = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Northstar Design", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(created.status(), await created.text()).toBe(201); const cid = (await created.json()).id as string;
  const base = `${API}/v1/business/companies/${cid}`;
  expect((await context.request.post(`${base}/verification/account`)).ok()).toBe(true);
  await page.goto(`/business/app/${cid}`);
  await expect(page.getByRole("heading", { name: "Your next role starts here.", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Build a clearer hiring rhythm.", exact: true })).toBeVisible();
  const nav = page.getByRole("navigation", { name: "Northstar Design workspaces", exact: true });
  await nav.getByRole("searchbox", { name: "Find a workspace", exact: true }).fill("coordination review");
  await expect(nav.getByRole("link")).toHaveText(["Review inbox"]);
  await nav.getByRole("searchbox", { name: "Find a workspace", exact: true }).fill("nothing matches");
  await expect(nav.getByRole("status")).toHaveText("No matching workspaces for your role.");
  await nav.getByRole("button", { name: "Clear workspace search" }).click();
  await expect(nav.getByRole("link")).toHaveCount(19);
  const job = await context.request.post(`${base}/jobs`, { data: { title: "Platform designer", description_html: "<p>Design clear and accessible workflows for a product team.</p>", workplace: "remote", must_haves: ["Accessible product design"] } });
  expect(job.status(), await job.text()).toBe(201); const jid = (await job.json()).id as string;
  expect((await context.request.post(`${base}/jobs/${jid}/publish`)).ok()).toBe(true);
  const candidate = await browser.newContext();
  const candidateEmail = `design-candidate-${crypto.randomUUID().slice(0, 8)}@example.com`;
  const file = execFileSync(resolve("apps/api/.venv/bin/python"), ["-c", "import io,sys; from docx import Document; d=Document(); d.add_paragraph('Fictional applicant designs accessible product workflows and interface systems.'); b=io.BytesIO(); d.save(b); sys.stdout.buffer.write(b.getvalue())"]);
  const application = await candidate.request.post(`${API}/v1/public/business/jobs/${jid}/apply`, { multipart: { name: "Fictional Designer", email: candidateEmail, consent: "true", notice_version: "2026-10-19.2", answers: "[]", file: { name: "resume.docx", mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document", buffer: file } } });
  expect(application.ok(), await application.text()).toBe(true);
  const token = await mailToken(candidateEmail, /\/application\/([\w-]+)/);
  expect((await candidate.request.post(`${API}/v1/public/business/applications/${token}/confirm`)).ok()).toBe(true);
  await candidate.close();
  await page.reload();
  await expect(page.getByRole("link", { name: "Platform designer", exact: true })).toBeVisible();
  await expect(page.getByRole("img", { name: /1 applications over 30 UTC calendar days/ })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: info.outputPath("business-dashboard-desktop.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const summary = page.locator("summary").filter({ hasText: "Browse workspaces" });
  await summary.click();
  await nav.getByRole("searchbox", { name: "Find a workspace", exact: true }).fill("policy");
  await nav.getByRole("link", { name: "Policy reviews", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/business/app/${cid}/knowledge-reviews$`));
  await expect(nav).toHaveCount(0);
  await expect(page.locator("#main")).toBeFocused();
  await summary.click();
  await nav.getByRole("searchbox", { name: "Find a workspace", exact: true }).focus();
  await page.keyboard.press("Escape");
  await expect(summary).toBeFocused();
  await expect(nav).toHaveCount(0);
  await summary.click();
  await nav.getByRole("searchbox", { name: "Find a workspace", exact: true }).fill("");
  await nav.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Dashboard", exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("business-dashboard-mobile-dark.png"), fullPage: true });
  await summary.click();
  await page.screenshot({ path: info.outputPath("business-navigation-mobile-dark.png") });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);

  // A client presentation fixture: verify the interviewer shell avoids a server-forbidden analytics request.
  const realCompany = await (await context.request.get(base)).json();
  const permissions = Object.fromEntries(Object.keys(realCompany.permissions).map(key => [key, key === "scorecards_only"]));
  await page.route(base, route => route.fulfill({ json: { ...realCompany, role: "interviewer", permissions } }));
  const analytics: string[] = [];
  page.on("request", request => { if (request.url() === `${base}/analytics`) analytics.push(request.url()); });
  await page.goto(`/business/app/${cid}`);
  await expect(page.getByRole("heading", { name: "Your interview workspace", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Hiring metrics", exact: true })).toHaveCount(0);
  expect(analytics).toEqual([]);
  await summary.click();
  await expect(nav.getByRole("link", { name: "Talent communities", exact: true })).toHaveCount(0);
  await expect(nav.getByRole("link", { name: "Settings", exact: true })).toHaveCount(0);
});
