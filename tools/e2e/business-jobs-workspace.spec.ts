import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";

test("Business jobs: discovery views, URL history, retry recovery, responsive design and editor handoff", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `roles-${crypto.randomUUID().slice(0, 8)}.com`; const email = `owner@${domain}`;
  const registered = await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Portfolio Owner", password: "correct horse battery" } });
  expect(registered.status(), await registered.text()).toBe(201);
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = /verify-email\?token=([\w-]+)/.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token } })).ok()).toBe(true);
  const created = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Northstar Roles", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(created.status(), await created.text()).toBe(201); const cid = (await created.json()).id as string; const base = `${API}/v1/business/companies/${cid}`;
  expect((await context.request.post(`${base}/verification/account`)).ok()).toBe(true);
  const home = `/business/app/${cid}/jobs`;
  const modules: string[] = [];
  page.on("request", request => modules.push(request.url()));
  await page.goto(home);
  await expect(page.getByRole("heading", { name: "A clear brief starts a better hiring process.", exact: true })).toBeVisible();
  const ids: string[] = [];
  for (const [title, department, location] of [["API engineer", "Platform", "London"], ["Product designer", "Product", "Berlin"], ["Operations lead", "Operations", "Bengaluru"]]) {
    const response = await context.request.post(`${base}/jobs`, { data: { title, department, locations: [location], description_html: "<p>Build clear, reliable workflows with a collaborative product team.</p>", workplace: "remote" } });
    expect(response.status(), await response.text()).toBe(201); ids.push((await response.json()).id as string);
  }
  expect((await context.request.post(`${base}/jobs/${ids[0]}/publish`)).ok()).toBe(true);
  let failing = true;
  await page.route(`${base}/jobs`, route => failing ? route.fulfill({ status: 500, json: { detail: "Temporary list error" } }) : route.continue());
  await page.reload();
  await expect(page.getByRole("button", { name: "Retry", exact: true })).toBeVisible();
  failing = false;
  await page.getByRole("button", { name: "Retry", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your hiring portfolio", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Retry", exact: true })).toHaveCount(0);
  const writes: string[] = [];
  page.on("request", request => { if (request.url().includes("/v1/business/") && !["GET", "OPTIONS"].includes(request.method())) writes.push(request.url()); });
  await page.getByRole("button", { name: "Drafts (2)", exact: true }).click();
  await page.getByLabel("Find a job", { exact: true }).fill("PRODUCT BERLIN");
  await expect(page.getByRole("list", { name: "Job cards", exact: true }).getByRole("heading")).toHaveText(["Product designer"]);
  await page.reload();
  await expect(page.getByLabel("Find a job", { exact: true })).toHaveValue("PRODUCT BERLIN");
  await expect(page.getByRole("button", { name: "Drafts (2)", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Table", exact: true }).click();
  await expect(page.getByRole("table", { name: "Jobs", exact: true }).getByRole("link", { name: "Product designer", exact: true })).toBeVisible();
  await page.goBack();
  await expect(page.getByRole("button", { name: "Cards", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.goForward();
  await expect(page.getByRole("button", { name: "Table", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Reset job filters", exact: true }).click();
  await page.getByLabel("Sort jobs", { exact: true }).selectOption("title");
  await expect(page.getByRole("list", { name: "Job cards", exact: true }).getByRole("heading")).toHaveText(["API engineer", "Operations lead", "Product designer"]);
  await page.getByLabel("Jobs with new applicants", { exact: true }).check();
  await expect(page.getByRole("heading", { name: "No jobs match this view.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Show all accessible jobs", exact: true }).click();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: info.outputPath("business-jobs-desktop.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("business-jobs-mobile-dark.png"), fullPage: true });
  await page.getByRole("button", { name: "Table", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  expect(writes).toEqual([]);
  expect(modules.some(url => /\/src\/business\/Jobs\.tsx(?:\?|$)|\/assets\/Jobs-/.test(url))).toBe(false);
  await page.getByRole("button", { name: "Cards", exact: true }).click();
  await page.getByRole("link", { name: "Edit role Product designer", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/business/app/${cid}/jobs/${ids[1]}/edit$`));
  await expect(page.getByRole("textbox", { name: "Job title (required)", exact: true })).toHaveValue("Product designer");
});
