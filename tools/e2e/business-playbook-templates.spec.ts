import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";

test("Automation drafts: templates, validation, stale settings, explicit activation and queue pagination", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `playbook-${crypto.randomUUID().slice(0, 8)}.com`; const email = `owner@${domain}`;
  const registered = await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Playbook Owner", password: "correct horse battery" } });
  expect(registered.status(), await registered.text()).toBe(201); const owner = (await registered.json()).user.id as string;
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = /verify-email\?token=([\w-]+)/.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token } })).ok()).toBe(true);
  const company = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Northstar Playbooks", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(company.status(), await company.text()).toBe(201); const cid = (await company.json()).id as string; const base = `${API}/v1/business/companies/${cid}`;
  expect((await context.request.post(`${base}/verification/account`)).ok()).toBe(true);
  const created = await context.request.post(`${base}/jobs`, { data: { title: "Platform engineer", description_html: "<p>Build clear, reliable engineering workflows for a product team.</p>", workplace: "remote" } });
  expect(created.status(), await created.text()).toBe(201); const jid = (await created.json()).id as string;
  expect((await context.request.post(`${base}/jobs/${jid}/publish`)).ok()).toBe(true);
  const endpoint = `${base}/jobs/${jid}/automation`;
  await page.goto(`/business/app/${cid}/automations`);
  await page.getByLabel("Job", { exact: true }).selectOption(jid);
  await expect(page.getByRole("heading", { name: "Role playbook", exact: true })).toBeVisible();
  const writes: string[] = []; page.on("request", request => { if (request.url().startsWith(base) && !["GET", "OPTIONS"].includes(request.method())) writes.push(request.url()); });
  await page.getByLabel("Default task owner", { exact: true }).selectOption(owner);
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Use Candidate response draft", exact: true }).click();
  await expect(page.getByLabel("Run these automations for Platform engineer", { exact: true })).not.toBeChecked();
  await expect(page.getByLabel("Default task owner", { exact: true })).toHaveValue(owner);
  await expect(page.getByRole("button", { name: "Run saved playbook now", exact: true })).toBeDisabled();
  const questions = page.getByRole("group", { name: "Candidate questions settings", exact: true });
  await questions.getByRole("spinbutton").fill("");
  await expect(questions.getByRole("checkbox", { name: "Candidate questions", exact: true })).toBeChecked();
  await expect(page.getByRole("button", { name: "Save playbook", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Preview conditions", exact: true })).toBeDisabled();
  await questions.getByRole("spinbutton").fill("24");
  await page.getByRole("button", { name: "Preview conditions", exact: true }).click();
  await expect(page.getByText("0 current follow-up conditions", { exact: true })).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download playbook draft", exact: true }).click();
  const savedFile = await download; const draft = JSON.parse(await readFile((await savedFile.path())!, "utf8"));
  expect(draft.working_draft.enabled).toBe(false); expect(draft.working_draft.owner).toBe(owner); expect(writes).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; window.scrollTo(0, 0); });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.getByRole("heading", { name: "Role playbook", exact: true }).locator("xpath=ancestor::section[1]").screenshot({ path: info.outputPath("automation-template-draft-mobile.png") });
  await page.getByRole("button", { name: "Save playbook", exact: true }).click();
  await expect(page.getByText("Automation settings saved and queue reconciled.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Run saved playbook now", exact: true })).toBeEnabled();
  await questions.getByRole("spinbutton").fill("36");
  const settings = await context.request.get(`${base}/automations`);
  expect(settings.ok(), await settings.text()).toBe(true);
  const source = (await settings.json()).jobs.find((job: { job_id: string }) => job.job_id === jid);
  const external = await context.request.put(endpoint, { data: { base_revision: source.revision, recipe: { ...source.recipe, question_hours: 12 } } });
  expect(external.ok(), await external.text()).toBe(true);
  await page.getByRole("button", { name: "Refresh queue", exact: true }).click();
  await expect(page.getByText("Saved playbook changed", { exact: true })).toBeVisible();
  await expect(questions.getByRole("spinbutton")).toHaveValue("36");
  await expect(page.getByRole("button", { name: "Save playbook", exact: true })).toBeDisabled();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Reload saved settings", exact: true }).click();
  await expect(questions.getByRole("spinbutton")).toHaveValue("12");
  await page.getByLabel("Run these automations for Platform engineer", { exact: true }).check();
  await page.getByRole("button", { name: "Save playbook", exact: true }).click();
  await expect(page.getByText(/Saved playbook enabled\./)).toBeVisible();
  expect((await context.request.post(`${base}/jobs/${jid}/pause`)).ok()).toBe(true);
  await page.getByRole("button", { name: "Refresh queue", exact: true }).click();
  await expect(page.getByText(/You can disable an existing playbook/)).toBeVisible();
  await page.getByLabel("Run these automations for Platform engineer", { exact: true }).uncheck();
  await page.getByRole("button", { name: "Save playbook", exact: true }).click();
  await expect(page.getByText(/Saved playbook disabled\./)).toBeVisible();
  // Presentation fixture for an owner removed from the latest eligible-coordinator list.
  await page.route(`${base}/automations`, async route => {
    const response = await route.fetch(); const body = await response.json();
    await route.fulfill({ response, json: { ...body, jobs: body.jobs.map((job: { job_id: string }) => job.job_id === jid ? { ...job, owners: [] } : job) } });
  });
  await page.getByRole("button", { name: "Refresh queue", exact: true }).click();
  await expect(page.getByRole("option", { name: "Saved owner is no longer available", exact: true })).toHaveCount(1);
  await expect(page.getByLabel("Default task owner", { exact: true })).toHaveValue(owner);
  await expect(page.getByRole("button", { name: "Save playbook", exact: true })).toBeDisabled();
  await page.getByLabel("Default task owner", { exact: true }).selectOption("");
  await page.getByRole("button", { name: "Save playbook", exact: true }).click();
  await expect(page.getByRole("button", { name: "Run saved playbook now", exact: true })).toBeEnabled();

  // A presentation fixture for an older pagination response; real task lifecycle coverage runs alongside this test.
  const task = { id: "old", application_id: "fixture-app", job_id: jid, job_title: "Platform engineer", name: "Fictional candidate", reference: "FIXTURE", kind: "manual", title: "Original open task", status: "open", assignee_id: null, due_at: new Date().toISOString(), snoozed_until: null, revision: 1, resolution: null, actionable: false };
  let release: (() => void) | undefined;
  await page.route(`${base}/hiring-tasks?*`, async route => {
    const params = new URL(route.request().url()).searchParams;
    if (params.has("after")) { await new Promise<void>(resolve => { release = resolve; }); await route.fulfill({ json: { items: [{ ...task, id: "late", title: "Late open page" }], next_after: null, counts: { open: 2 }, overdue: 0, as_of: new Date().toISOString() } }); return; }
    const done = params.get("status") === "done";
    await route.fulfill({ json: { items: [{ ...task, id: done ? "done" : "old", title: done ? "Current handled task" : task.title, status: done ? "done" : "open" }], next_after: done ? null : "cursor", counts: { open: done ? 0 : 1, done: done ? 1 : 0 }, overdue: 0, as_of: new Date().toISOString() } });
  });
  await page.getByRole("button", { name: "Refresh queue", exact: true }).click();
  await expect(page.getByRole("heading", { name: task.title, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Load more tasks", exact: true }).click();
  await expect.poll(() => Boolean(release)).toBe(true);
  await page.getByLabel("Task status", { exact: true }).selectOption("done");
  await expect(page.getByRole("heading", { name: "Current handled task", exact: true })).toBeVisible();
  const late = page.waitForResponse(response => response.url().includes("after=cursor"));
  release!(); await (await late).finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(page.getByRole("heading", { name: "Late open page", exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Current handled task", exact: true })).toBeVisible();
});
