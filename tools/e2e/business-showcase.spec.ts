import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";

const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";

test("Business showcase: workflow tour, discovery, goal isolation, download and accessible responsive visuals", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  await page.goto("/business");
  await expect(page.getByRole("heading", { level: 1 })).toContainText("One connected orbit");
  await page.screenshot({ path: info.outputPath("business-hero-desktop.png") });
  await page.getByRole("button", { name: "Unblock the team", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Less chasing. More visible next steps." })).toBeVisible();
  await page.getByRole("link", { name: "Build this rollout plan" }).click();
  await expect(page.getByLabel("Rollout goal", { exact: true })).toHaveValue("coordinate");
  await expect(page).toHaveURL(/rollout=coordinate#business-rollout/);
  await expect(page.getByRole("heading", { name: "Turn the toolkit into a team plan." })).toBeInViewport();
  await page.getByRole("checkbox", { name: "1. Find where work is waiting" }).check();
  await expect(page.getByRole("progressbar", { name: "Unblock the team checklist progress" })).toHaveAttribute("value", "1");
  await page.getByLabel("Rollout goal", { exact: true }).selectOption("community");
  await expect(page.getByRole("checkbox", { name: "1. Define the community purpose" })).not.toBeChecked();
  await page.getByLabel("Rollout goal", { exact: true }).selectOption("coordinate");
  await expect(page.getByRole("checkbox", { name: "1. Find where work is waiting" })).toBeChecked();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download checklist", exact: true }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe("orbit-business-coordinate-rollout.md");
  const content = await readFile((await download.path())!, "utf8");
  expect(content).toContain("## [x] 1. Find where work is waiting");
  expect(content).toContain("does not verify or change company setup");
  await page.getByRole("button", { name: "Reset this checklist", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "1. Find where work is waiting" })).not.toBeChecked();
  const directory = page.getByRole("region", { name: "Find the workspace for your next step." });
  await directory.getByLabel("Find a Business tool").fill("cited");
  await expect(directory.getByRole("heading", { level: 3 })).toHaveText(["Knowledge Studio"]);
  await expect(directory.getByRole("link", { name: "Open Knowledge Studio" })).toHaveAttribute("href", "/business/app?tool=knowledge");
  await directory.getByRole("button", { name: "Plan", exact: true }).click();
  await expect(directory.getByText("No tools match these filters.")).toBeVisible();
  await directory.getByRole("button", { name: "Reset tool filters" }).click();
  await expect(directory.getByRole("heading", { level: 3 })).toHaveCount(15);
  await directory.getByLabel("Find a Business tool").fill("AI");
  await expect(directory.getByRole("heading", { level: 3 })).toHaveCount(6);
  await directory.getByLabel("Find a Business tool").fill("");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.evaluate(() => document.fonts.ready);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { localStorage.setItem("orbit.theme", "dark"); document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  expect(await page.locator("svg .motion-ok\\:animate-scale-in").evaluateAll(nodes => nodes.every(node => getComputedStyle(node).animationName === "none"))).toBe(true);
  await page.screenshot({ path: info.outputPath("business-hero-mobile-dark.png") });
  await page.getByRole("group", { name: "Explore Business workflows" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("business-tour-mobile-dark.png") });
  await page.reload();
  await expect(page.getByLabel("Rollout goal", { exact: true })).toHaveValue("coordinate");
  await expect(page.getByRole("checkbox", { name: "1. Find where work is waiting" })).not.toBeChecked();
});

test("Business launchpad: the company chooser opens the selected tool and checklist edits make no company writes", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `showcase-${crypto.randomUUID().slice(0, 8)}.com`;
  const email = `owner@${domain}`;
  const registered = await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Business Owner", password: "correct horse battery" } });
  expect(registered.status(), await registered.text()).toBe(201);
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = /verify-email\?token=([\w-]+)/.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token } })).ok()).toBe(true);
  const created = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Showcase Team", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(created.status(), await created.text()).toBe(201);
  const cid = (await created.json()).id as string;
  await page.goto("/business/app?tool=launchpad");
  await page.getByRole("link", { name: /Showcase Team/ }).click();
  await expect(page).toHaveURL(new RegExp(`/business/app/${cid}/launchpad$`));
  await expect(page.getByRole("heading", { name: "Business launchpad", exact: true })).toBeVisible();
  const writes: string[] = [];
  page.on("request", request => { if (request.url().includes("/v1/business/") && !["GET", "OPTIONS"].includes(request.method())) writes.push(request.url()); });
  await page.getByLabel("Rollout goal", { exact: true }).selectOption("knowledge");
  await page.getByRole("checkbox", { name: "1. Import and review a policy draft" }).check();
  await expect(page.getByRole("link", { name: "Open Policy reviews", exact: true }).first()).toHaveAttribute("href", `/business/app/${cid}/knowledge-reviews`);
  expect(writes).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath("business-launchpad-mobile.png") });
  await page.getByLabel("Find a Business tool").fill("talent");
  await page.getByRole("link", { name: "Open Talent communities", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/business/app/${cid}/talent$`));
  await expect(page.getByRole("heading", { name: "Talent communities", exact: true })).toBeVisible();
});
