import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
const API = process.env.ORBIT_TEST_API_URL ?? "http://127.0.0.1:8000";
const OUTBOX = process.env.ORBIT_TEST_OUTBOX ?? "apps/api/e2e-outbox.txt";

test("Reading workspace: direct links, exact source, local controls and stale-refresh guards", async ({ page, context }, info) => {
  await context.addInitScript(() => localStorage.setItem("orbit.cookies.v1", "1"));
  const domain = `reading-ui-${crypto.randomUUID().slice(0, 8)}.com`; const email = `owner@${domain}`;
  expect((await context.request.post(`${API}/v1/auth/register`, { data: { email, name: "Reading Owner", password: "correct horse battery" } })).status()).toBe(201);
  let token = "";
  await expect.poll(async () => { const mail = (await readFile(OUTBOX, "utf8")).split("--- to=").filter(row => row.startsWith(email)).at(-1) ?? ""; token = /verify-email\?token=([\w-]+)/.exec(mail)?.[1] ?? ""; return token.length; }).toBeGreaterThan(10);
  expect((await context.request.post(`${API}/v1/auth/verify-email/confirm`, { data: { token } })).ok()).toBe(true);
  const created = await context.request.post(`${API}/v1/business/companies`, { data: { name: "Northstar Reading", website: `https://${domain}`, size: "11-50", country: "IN" } });
  expect(created.status(), await created.text()).toBe(201); const cid = (await created.json()).id as string;
  const base = `${API}/v1/business/companies/${cid}`; const endpoint = `${base}/knowledge-reading`;
  const home = `/business/app/${cid}/knowledge-reading`;
  const body = ["Read the published interview guidance before meeting a candidate. Record independent observations and distinguish evidence from assumptions. ".repeat(3), "Ask the coordinator to clarify any uncertain instruction. Keep personal details out of shared process notes and discuss role requirements consistently. ".repeat(2), "Use the debrief to discuss differences in observed evidence. A reading acknowledgement records your own statement of reading, not a test result. ".repeat(2)].join("\n\n").trim();
  const draft = await context.request.post(`${base}/knowledge`, { data: { request_id: crypto.randomUUID(), data: { title: "Independent panel guidance", body, category: "interview", audience: "all_hiring", review_due: "" } } });
  expect(draft.ok(), await draft.text()).toBe(true); const doc = await draft.json();
  expect((await context.request.post(`${base}/knowledge/${doc.id}/actions`, { data: { base_revision: doc.revision, action: "publish", note: "Reviewed the source wording for the hiring team." } })).ok()).toBe(true);
  const writes: string[] = [];
  page.on("request", request => { if (request.url().includes("/v1/business/") && !["GET", "OPTIONS"].includes(request.method())) writes.push(request.url()); });
  await page.goto(home);
  await expect(page.getByRole("heading", { name: "Read the source. Keep your context.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Read Independent panel guidance", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`document=${doc.id}`));
  await expect(page.getByTestId("published-reading-text")).toHaveText(body);
  expect(await page.getByTestId("published-reading-text").textContent()).toBe(body);
  await page.getByLabel("Reading text size", { exact: true }).selectOption("large");
  await page.getByRole("button", { name: "Expand reading area", exact: true }).click();
  await page.getByText("Navigate published passages (3)", { exact: true }).click();
  await page.getByRole("button", { name: /^Passage 2/ }).click();
  await expect(page.locator(`#reading-${doc.id}-passage-2`)).toBeFocused();
  expect(await page.getByTestId("published-reading-text").textContent()).toBe(body);
  await expect(page.getByRole("button", { name: "Record my acknowledgement", exact: true })).toBeDisabled();
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath("business-reader-desktop.png"), fullPage: true });
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.reload();
  await expect(page.getByTestId("published-reading-text")).toHaveText(body);
  await expect(page.getByLabel("Reading text size", { exact: true })).toHaveValue("regular");
  await expect(page.getByLabel("I personally read the full published text shown above.", { exact: true })).not.toBeChecked();
  await page.goBack();
  await expect(page.getByRole("heading", { name: "My reading list", exact: true })).toBeVisible();
  await page.goForward();
  await expect(page.getByTestId("published-reading-text")).toHaveText(body);
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.evaluate(() => { document.documentElement.classList.add("dark"); document.documentElement.dataset.motion = "reduced"; });
  await page.getByLabel("Reading text size", { exact: true }).selectOption("large");
  await page.getByRole("button", { name: "Expand reading area", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath("business-reader-mobile-dark.png"), fullPage: true });
  await page.getByRole("button", { name: "Back to reading list", exact: true }).click();
  const validList = await (await context.request.get(endpoint)).json();
  let release: (() => void) | undefined; let calls = 0;
  await page.route(endpoint, async route => {
    if (++calls === 1) { await new Promise<void>(resolve => { release = resolve; }); await route.fulfill({ status: 503, json: { detail: "Older refresh failed" } }); }
    else await route.fulfill({ json: validList });
  });
  await page.getByRole("button", { name: "Refresh reading list", exact: true }).click();
  await expect.poll(() => Boolean(release)).toBe(true);
  const success = page.waitForResponse(response => response.url() === endpoint && response.status() === 200);
  await page.getByRole("button", { name: "Refresh reading list", exact: true }).click();
  await (await success).finished();
  const late = page.waitForResponse(response => response.url() === endpoint && response.status() === 503);
  release!(); await (await late).finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(page.getByText("Orbit had a problem. Try again shortly.", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Read Independent panel guidance", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Team coverage", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Current-member reading coverage", exact: true })).toBeVisible();
  const coverage = `${endpoint}/coverage`;
  const validCoverage = await (await context.request.get(coverage)).json();
  let releaseCoverage: (() => void) | undefined; let coverageCalls = 0;
  await page.route(coverage, async route => {
    if (++coverageCalls === 1) { await new Promise<void>(resolve => { releaseCoverage = resolve; }); await route.fulfill({ status: 503, json: { detail: "Older coverage refresh failed" } }); }
    else await route.fulfill({ json: validCoverage });
  });
  await page.getByRole("button", { name: "Refresh coverage", exact: true }).click();
  await expect.poll(() => Boolean(releaseCoverage)).toBe(true);
  const coverageSuccess = page.waitForResponse(response => response.url() === coverage && response.status() === 200);
  await page.getByRole("button", { name: "Refresh coverage", exact: true }).click();
  await (await coverageSuccess).finished();
  const oldCoverage = page.waitForResponse(response => response.url() === coverage && response.status() === 503);
  releaseCoverage!(); await (await oldCoverage).finished();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(page.getByText("Orbit had a problem. Try again shortly.", { exact: true })).toHaveCount(0);
  await page.goto(`${home}?document=invalid-document`);
  await expect(page.getByText("This document link is invalid. Choose published guidance from the reading list.", { exact: true })).toBeVisible();
  expect(writes).toEqual([]);
  const list = await (await context.request.get(endpoint)).json();
  expect(list.items[0].acknowledged).toBe(false);
});
