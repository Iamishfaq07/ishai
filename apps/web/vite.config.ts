import { createHash } from "node:crypto";
import { appendFileSync, copyFileSync, createReadStream, existsSync, mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { defineConfig, loadEnv, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import { inlineTheme } from "./inlineTheme.js";
import { policyPages } from "./policyPages.js";
import { questionBank } from "./questionBank.js";

const TURNSTILE = "https://challenges.cloudflare.com";
const RAZORPAY_SCRIPTS = "https://checkout.razorpay.com";
const RAZORPAY_FRAMES = "https://api.razorpay.com https://checkout.razorpay.com";
const RAZORPAY_CONNECT = "https://api.razorpay.com https://lumberjack.razorpay.com";

/** `https://api.example.com` → [`https://api.example.com`, `wss://api.example.com`]; relative URLs are 'self'. */
function origins(url: string | undefined): string[] {
  if (!url || !/^https?:\/\//.test(url)) return [];
  const { protocol, host } = new URL(url);
  return [`${protocol}//${host}`, `${protocol === "https:" ? "wss:" : "ws:"}//${host}`];
}

/** The Content-Security-Policy for the built app. One policy: public/_headers must not add a second. */
export function contentSecurityPolicy(inlineScripts: string[], env: Record<string, string | undefined>): string {
  const hashes = inlineScripts.map((s) => `'sha256-${createHash("sha256").update(s).digest("base64")}'`);
  const connect = [
    "'self'",
    TURNSTILE,
    ...RAZORPAY_CONNECT.split(" "),
    ...origins(env.VITE_API_URL),
    ...origins(env.VITE_LIVE_URL),
    ...origins(env.VITE_API_DIRECT_URL),
  ];
  return [
    "default-src 'self'",
    // 'wasm-unsafe-eval': the camera coach's face model runs as WebAssembly, served from this site (never eval).
    `script-src 'self' 'wasm-unsafe-eval' ${hashes.join(" ")} ${TURNSTILE} ${RAZORPAY_SCRIPTS}`.replace(/\s+/g, " "),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https://cdn.razorpay.com",
    "font-src 'self' data:",
    "media-src 'self' blob: data:",
    "worker-src 'self' blob:",
    `connect-src ${[...new Set(connect)].join(" ")}`,
    `frame-src ${TURNSTILE} ${RAZORPAY_FRAMES}`,
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "manifest-src 'self'",
    "upgrade-insecure-requests",
  ].join("; ");
}

/**
 * Appends the security headers to the build's `_headers` (Cloudflare reads it; `public/_headers` holds the cache
 * rules only). The CSP is computed from the finished index.html, so the inline theme script's hash can't go stale,
 * and from the API/live URLs this build talks to. Do not also put a CSP in public/_headers: both would apply.
 */
function securityHeaders(mode: string): Plugin {
  let outDir = "dist";
  return {
    name: "orbit-security-headers",
    apply: "build",
    configResolved(config) {
      outDir = config.build.outDir;
    },
    writeBundle() {
      const env = loadEnv(mode, process.cwd(), "VITE_");
      const html = readFileSync(join(outDir, "index.html"), "utf8");
      const inline = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1] ?? "");
      const file = join(outDir, "_headers");
      const lead = existsSync(file) ? "\n" : "";
      appendFileSync(
        file,
        `${lead}# Security headers (generated by vite.config.ts at build time).
/*
  Content-Security-Policy: ${contentSecurityPolicy(inline, env)}
  Strict-Transport-Security: max-age=63072000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(self), geolocation=(), payment=(), usb=(), microphone=(self), display-capture=(self)
`,
      );
    },
  };
}

/**
 * The camera coach's WebAssembly (MediaPipe Tasks Vision, from node_modules): served at /mediapipe/wasm/ in dev and
 * copied there in the build, so the face model runs from this site and the browser never fetches it from a CDN. The
 * model file itself is public/mediapipe/face_landmarker.task (Apache-2.0, from Google's MediaPipe model card).
 */
const MEDIAPIPE_WASM = ["vision_wasm_internal.js", "vision_wasm_internal.wasm", "vision_wasm_nosimd_internal.js", "vision_wasm_nosimd_internal.wasm"];
function mediapipeWasm(): Plugin {
  const dir = join(dirname(createRequire(import.meta.url).resolve("@mediapipe/tasks-vision")), "wasm");
  let outDir = "dist";
  return {
    name: "orbit-mediapipe-wasm",
    configResolved(config) {
      outDir = config.build.outDir;
    },
    configureServer(server) {
      server.middlewares.use("/mediapipe/wasm", (req, res, next) => {
        const name = (req.url ?? "").replace(/^\//, "").split("?")[0] ?? "";
        if (!MEDIAPIPE_WASM.includes(name)) return next();
        res.setHeader("Content-Type", name.endsWith(".wasm") ? "application/wasm" : "text/javascript");
        createReadStream(join(dir, name)).pipe(res);
      });
    },
    writeBundle() {
      const target = join(outDir, "mediapipe", "wasm");
      mkdirSync(target, { recursive: true });
      for (const name of MEDIAPIPE_WASM) copyFileSync(join(dir, name), join(target, name));
    },
  };
}

export default defineConfig(({ mode, isSsrBuild }) => ({
  plugins: [react(), questionBank(), ...(isSsrBuild ? [] : [inlineTheme(), securityHeaders(mode), mediapipeWasm(), policyPages()])],
  server: { port: 5173, strictPort: true },
  // `vite build --ssr src/prerender/entry.tsx`: the public pages' build-time render (scripts/prerender.mjs runs it).
  // Everything is bundled into one Node file, so it runs from .prerender/ without resolving packages there.
  ssr: { noExternal: true },
  ...(isSsrBuild
    ? { build: { outDir: ".prerender", emptyOutDir: true, copyPublicDir: false, rolldownOptions: { output: { entryFileNames: "[name].mjs" } } } }
    : {}),
}));
